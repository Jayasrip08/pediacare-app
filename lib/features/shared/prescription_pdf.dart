import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../core/utils.dart';
import '../../models/models.dart';

/// Builds a printable A4 prescription. Uses only Latin characters (default PDF fonts).
Future<Uint8List> buildPrescriptionPdf(Prescription p) async {
  final navy = PdfColor.fromHex('#0F1E3D');
  final orange = PdfColor.fromHex('#F7861E');
  final grey = PdfColor.fromHex('#6B7592');
  final line = PdfColor.fromHex('#E5E8F0');

  pw.Widget cell(String text, {bool bold = false, PdfColor? color}) => pw.Padding(
        padding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 7),
        child: pw.Text(text,
            style: pw.TextStyle(
                fontSize: 10.5,
                fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
                color: color)),
      );

  final doc = pw.Document(title: 'Prescription', author: p.clinicName ?? 'PediaCare');
  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(32),
      footer: (_) => pw.Align(
        alignment: pw.Alignment.centerRight,
        child: pw.Text('Generated by PediaCare - InnoLift Ventures',
            style: pw.TextStyle(fontSize: 8, color: grey)),
      ),
      build: (_) => [
        pw.Container(
          padding: const pw.EdgeInsets.all(18),
          decoration: pw.BoxDecoration(color: navy, borderRadius: pw.BorderRadius.circular(10)),
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text(p.clinicName ?? 'Clinic',
                  style: pw.TextStyle(
                      color: PdfColors.white, fontSize: 20, fontWeight: pw.FontWeight.bold)),
              if (p.clinicAddress != null)
                pw.Padding(
                  padding: const pw.EdgeInsets.only(top: 4),
                  child: pw.Text(p.clinicAddress!,
                      style: const pw.TextStyle(color: PdfColors.white, fontSize: 10)),
                ),
              if (p.clinicPhone != null)
                pw.Text('Phone: ${p.clinicPhone}',
                    style: const pw.TextStyle(color: PdfColors.white, fontSize: 10)),
            ],
          ),
        ),
        pw.SizedBox(height: 14),
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(p.doctorName ?? 'Doctor',
                style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold)),
            pw.Text('Date: ${fmtDate(p.createdAt)}', style: const pw.TextStyle(fontSize: 11)),
          ],
        ),
        pw.Divider(color: line),
        pw.Row(
          children: [
            pw.Expanded(
                child: pw.Text('Patient: ${p.childName ?? '-'}',
                    style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold))),
            if (p.childDob != null)
              pw.Expanded(
                  child: pw.Text('Age: ${ageLabel(p.childDob!, p.createdAt)}',
                      style: const pw.TextStyle(fontSize: 11))),
            pw.Expanded(
                child: pw.Text('Weight: ${numFmt(p.weightKg)} kg',
                    style: const pw.TextStyle(fontSize: 11))),
          ],
        ),
        if (p.diagnosis != null) ...[
          pw.SizedBox(height: 6),
          pw.Text('Diagnosis: ${p.diagnosis}', style: const pw.TextStyle(fontSize: 11)),
        ],
        pw.SizedBox(height: 16),
        pw.Text('Rx',
            style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold, color: orange)),
        pw.SizedBox(height: 6),
        pw.Table(
          border: pw.TableBorder.all(color: line),
          columnWidths: const {
            0: pw.FlexColumnWidth(3),
            1: pw.FlexColumnWidth(2.4),
            2: pw.FlexColumnWidth(2.6),
          },
          children: [
            pw.TableRow(
              decoration: pw.BoxDecoration(color: PdfColor.fromHex('#F6F7FB')),
              children: [
                cell('Medicine', bold: true),
                cell('Dose', bold: true),
                cell('How long', bold: true),
              ],
            ),
            for (final i in p.items)
              pw.TableRow(children: [
                pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
                  cell(i.name, bold: true),
                  if (i.instructions != null && i.instructions!.isNotEmpty)
                    pw.Padding(
                      padding: const pw.EdgeInsets.fromLTRB(8, 0, 8, 7),
                      child: pw.Text(i.instructions!,
                          style: pw.TextStyle(fontSize: 9, color: grey)),
                    ),
                ]),
                cell(i.doseLabel),
                cell('${i.timesPerDay} time(s) a day\nfor ${i.durationDays} day(s)'),
              ]),
          ],
        ),
        if (p.followUpDate != null) ...[
          pw.SizedBox(height: 14),
          pw.Text('Follow-up / review on: ${fmtDate(p.followUpDate!)}',
              style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold, color: orange)),
        ],
        if (p.notes != null) ...[
          pw.SizedBox(height: 10),
          pw.Text('Advice: ${p.notes}', style: const pw.TextStyle(fontSize: 11)),
        ],
        pw.SizedBox(height: 28),
        pw.Text(
          'Doses are confirmed by the prescribing doctor. Do not change the dose without '
          'consulting your doctor.',
          style: pw.TextStyle(fontSize: 9, color: grey),
        ),
      ],
    ),
  );
  return doc.save();
}
